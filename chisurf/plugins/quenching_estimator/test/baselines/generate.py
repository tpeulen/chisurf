"""Regenerate the numeric baselines in this directory.

    <arm64>/bin/python chisurf/plugins/quenching_estimator/test/baselines/generate.py

**A green suite does not tell you an accessible volume is right.** The grid was
once transposed x<->z and still overlapped the truth by 83 % of its voxels: the
point count, the bounding box and the total volume were all correct, only the
*shape* was mirrored, so the contact volume landed on the wrong side of the
protein and donors came out unquenched. Nothing in the suite noticed. These
baselines exist so a change that moves a number has to *say* which number and
by how much.

The rule that comes with them
([okf/specs/programme-2026-07.md](../../okf/specs/programme-2026-07.md),
decision 13): **a baseline may only be regenerated by a commit whose
`okf/log.md` entry accounts for every moved number.** Regenerating to make a
test pass, without that, is the failure mode this is meant to prevent.

The numba cache is cleared first, on purpose: `@njit(cache=True)` kernels only
re-read configuration when they actually compile, so a warm cache can hide a
compile-time failure entirely and produce a baseline from stale code.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

TEST_DIR = Path(__file__).resolve().parents[1]
#: The checkout root (``chisurf/``'s parent), so the script runs from anywhere.
REPO_ROOT = Path(__file__).resolve().parents[5]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

BASELINE_DIR = Path(__file__).resolve().parent

#: 148L chain E. These three are labelable and quenching under **both**
#: backends, which was the constraint when there were two. (LabelLib went with
#: LabelLib's retirement; the sites are kept because they are the ones the baselines pin.)
#: LabelLib labels
#: only 43 of this chain's 151 CB sites.
SITES = (96, 139, 129)

#: The widest-separated pair labelable under both backends (64.0 A), used for
#: the distance metrics and the FRET channel.
FRET_PAIR = (55, 124)

STRUCTURE = TEST_DIR / "148l.pdb"

#: Multi-chain, for the residue-identity work. Chain B's residue 40 and chain
#: A's residue 40 are different residues, and `residue_dict` used to merge them.
MULTICHAIN = TEST_DIR / "data" / "mc4r_dimer.cif"

#: Fixed so the Monte-Carlo noise is not what moves between runs.
SEED = 5

#: The accessible volume every baseline is taken with, stated rather than left to the
#: default. The baselines were recorded at QuEst's old default (21.5/0.5/3.5); the
#: default is IMP.bff's now (linker width 4.5 A), at which E96, E129 and E139 have
#: no volume at all -- so a baseline that read the default would measure nothing.
AV_PARAMETER = {"linker_length": 21.5, "linker_width": 0.5, "radius1": 3.5}


def clear_numba_cache() -> int:
    removed = 0
    for cache in TEST_DIR.parent.rglob("__pycache__"):
        for artefact in list(cache.glob("*.nbi")) + list(cache.glob("*.nbc")):
            artefact.unlink()
            removed += 1
    return removed


def _project(residue: int, *, structure: Path = STRUCTURE, chain: str = "E", acceptor=None):
    from chisurf.plugins.quenching_estimator.core.dye_diffusion import default_amino_acid_interactions

    donor = {
        "name": "D0",
        "D": 7.0,
        "random_seed": SEED,
        "attachment": {"chain": chain, "residue": residue, "atom": "CB"},
    }
    dyes = [donor]
    if acceptor is not None:
        dyes.append(
            {
                "name": "A0",
                "D": 7.0,
                "random_seed": SEED,
                "attachment": {"chain": chain, "residue": acceptor, "atom": "CB"},
                "av_parameter": dict(AV_PARAMETER),
            }
        )
    return {
        "tau0": 4.2,
        "n_photons": 4000,
        "t_max": 400.0,
        "t_step": 0.02,
        "dg": 0.5,
        "critical_distance": 8.5,
        "slow_radius": 8.5,
        "av_parameter": dict(AV_PARAMETER),
        "amino_acid_interactions": default_amino_acid_interactions(slow_factor=0.1),
        "attachment": {"chain": chain, "residue": residue, "atom": "CB"},
        "pdb": str(structure),
        "n_bins": 64,
        "parallel_trajectories": 1,
        "fret": {
            "enabled": acceptor is not None,
            "R0": 52.0,
            "dyes": dyes,
        },
    }


def _round(value, digits=6):
    if value is None:
        return None
    return round(float(value), digits)


def measure_av(structure: Path, chain: str, residue: int, backend: str) -> dict:
    """The geometry, before any simulation touches it."""
    import numpy as np

    from chisurf.plugins.quenching_estimator.core.av import AV

    av = AV(
        str(structure),
        chain_identifier=chain,
        residue_seq_number=residue,
        atom_name="CB",
        simulation_grid_resolution=0.5,
        save_av=False,
        verbose=False,
        av_backend=backend,
        **AV_PARAMETER,
    )
    points = np.asarray(av.points, dtype=float)
    density = np.asarray(av.density)
    centroid = points.mean(axis=0)
    return {
        "ng": int(av.ng),
        "n_points": int(points.shape[0]),
        "occupied_voxels": int((density > 0).sum()),
        "x0": [_round(v, 4) for v in np.asarray(av.x0, dtype=float)],
        # The centroid catches a *translation* the point count cannot: a grid
        # half a voxel out has exactly the same number of points.
        "points_centroid": [_round(v, 4) for v in centroid],
        # And this catches a transpose, which a centroid can miss on a
        # near-spherical cloud: the principal extents in each axis.
        "extent": [_round(v, 4) for v in (points.max(axis=0) - points.min(axis=0))],
    }


def measure_simulation(project: dict) -> dict:
    from chisurf.plugins.quenching_estimator.core import simulate_project

    result = simulate_project(project, save_outputs=False, render_data=False)
    return {
        "quantum_yield_donor": _round(result.quantum_yield_donor),
        "lifetime_donor": _round(result.lifetime_donor),
        "collisions_fraction": _round(result.collisions_fraction),
        "av_volume": _round(result.av_volume, 3),
        "contact_volume": _round(result.contact_volume, 3),
        "contact_to_free_ratio": _round(result.contact_to_free_ratio),
        "donor_counts_total": _round(float(result.donor_counts.sum()), 3),
        "fret_efficiency": _round(result.fret_efficiency),
        "quantum_yield_fret": _round(result.quantum_yield_fret),
    }


def measure_distances(chain: str, pair: tuple[int, int], backend: str) -> dict:
    from chisurf.plugins.quenching_estimator.core.av import AV

    def build(residue):
        return AV(
            str(STRUCTURE),
            chain_identifier=chain,
            residue_seq_number=residue,
            atom_name="CB",
            simulation_grid_resolution=0.5,
            save_av=False,
            verbose=False,
            av_backend=backend,
            **AV_PARAMETER,
        )

    donor, acceptor = build(pair[0]), build(pair[1])
    return {
        "pair": list(pair),
        "rda_mean": _round(donor.dRDA(acceptor), 4),
        "rda_mean_e": _round(donor.dRDAE(acceptor), 4),
        "rmp": _round(donor.dRmp(acceptor), 4),
    }


def measure_coarse_graining(structure: Path) -> dict:
    """Residue identity, which multi-chain structures get wrong.

    `residue_dict` is keyed on `res_id` alone, so chain B's residue 40 merges
    into chain A's. Recording the CB coordinates of the colliding ids is what
    makes that visible as a number rather than as an argument.
    """
    import numpy as np

    from chisurf.plugins.quenching_estimator.core.structure import Structure

    coarse = Structure(str(structure), make_coarse=True, verbose=False)
    atoms = coarse.atoms
    cb = atoms[atoms["atom_name"] == "CB"]
    chains = sorted({str(c) for c in atoms["chain"]})
    duplicated = 0
    seen: dict[int, int] = {}
    for res_id in cb["res_id"]:
        seen[int(res_id)] = seen.get(int(res_id), 0) + 1
    duplicated = sum(1 for count in seen.values() if count > 1)
    return {
        "chains": chains,
        "n_atoms": int(atoms.shape[0]),
        "n_cb": int(cb.shape[0]),
        "n_residue_ids_with_more_than_one_cb": duplicated,
        "cb_centroid": [_round(v, 4) for v in np.asarray(cb["coord"], dtype=float).mean(axis=0)],
    }


def build(backend: str) -> dict:
    # `simulate_project` builds its own AV and reads the backend from the
    # environment, not from an argument. Without this the simulation half of
    # every baseline is measured on whichever backend `resolve_av_backend`
    # picks -- which made both files identical on the first run, while their
    # accessible volumes differed by 7000 points.
    os.environ["QUEST_AV_BACKEND"] = backend
    baseline = {
        "backend": backend,
        "structure": STRUCTURE.name,
        "seed": SEED,
        "grid_resolution": 0.5,
        "accessible_volumes": {},
        "simulations": {},
    }
    for residue in SITES:
        key = f"E{residue}"
        print(f"  {backend}: AV {key}", flush=True)
        baseline["accessible_volumes"][key] = measure_av(STRUCTURE, "E", residue, backend)
        print(f"  {backend}: simulate {key}", flush=True)
        baseline["simulations"][key] = measure_simulation(_project(residue))

    print(f"  {backend}: distances E{FRET_PAIR[0]}-E{FRET_PAIR[1]}", flush=True)
    baseline["distances"] = measure_distances("E", FRET_PAIR, backend)

    print(f"  {backend}: FRET E{FRET_PAIR[0]}->E{FRET_PAIR[1]}", flush=True)
    baseline["fret"] = measure_simulation(_project(FRET_PAIR[0], acceptor=FRET_PAIR[1]))

    print(f"  {backend}: coarse-graining", flush=True)
    baseline["coarse_graining"] = {
        "148l.pdb": measure_coarse_graining(STRUCTURE),
        "mc4r_dimer.cif": measure_coarse_graining(MULTICHAIN),
    }
    return baseline


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--backend", choices=("imp_bff",), action="append")
    parser.add_argument(
        "--keep-numba-cache",
        action="store_true",
        help="Skip clearing the numba cache. Only for debugging this script.",
    )
    args = parser.parse_args()

    if not args.keep_numba_cache:
        print(f"cleared {clear_numba_cache()} numba cache artefacts")

    from chisurf.plugins.quenching_estimator.core.av import available_av_backends

    wanted = args.backend or list(available_av_backends())
    missing = [b for b in wanted if b not in available_av_backends()]
    if missing:
        print(f"unavailable in this interpreter: {', '.join(missing)}", file=sys.stderr)
        return 1

    for backend in wanted:
        print(f"backend {backend}")
        payload = build(backend)
        target = BASELINE_DIR / f"{backend}.json"
        target.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf8")
        print(f"wrote {target.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    os.environ.setdefault("QUEST_RUNS_DIR", "/tmp/quest-baseline-jobs")
    raise SystemExit(main())
