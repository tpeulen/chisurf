"""Coherent, explicitly synthetic PIE instrument; no device discovery or I/O.

The simulator shares laser, shutter and diode state with the actual GUI. Photon
batches are generated by tttrlib, then gated by that state. Its calibration and
acceptance values are test fixtures, never laboratory reference measurements.
"""
from __future__ import annotations

from dataclasses import replace
import time

import numpy as np

from .laser import SimLaser, laser_diode_threshold
from .realism import IDEAL
from .sources import PhotonBatch, PhotonSource, Population, SimulatedPieSource, SourceUnavailable


def laser_diode_power_fraction(drive_pct: float, threshold_pct: float) -> float:
    """Emulate the typical L-I power curve of a semiconductor laser diode.

    In PicoQuant hardware (e.g. Sepia II, PDL drivers), the user sets driver power (0..100%).
    Blue / Green laser diodes (e.g. 488 nm) typically have minimum driver power ~35%.
    Red laser diodes (e.g. 640 nm) typically have minimum driver power ~47%.

    Below threshold: spontaneous emission (LED mode) with very low optical output.
    At threshold: stimulated emission begins.
    Above threshold: stimulated emission increases following the laser diode L-I curve up to 100% drive.
    """
    d = max(0.0, min(100.0, float(drive_pct)))
    d_th = max(1.0, min(95.0, float(threshold_pct)))
    f_sp = 0.002  # spontaneous emission fraction at threshold (~0.2% of max power)
    if d <= d_th:
        return f_sp * (d / d_th)
    xi = (d - d_th) / (100.0 - d_th)
    return f_sp + (1.0 - f_sp) * xi


def laser_diode_drive_for_power(power_uw: float, max_uw: float, threshold_pct: float) -> float:
    """The diode drive (%) that delivers *power_uw* of a head whose maximum is *max_uw*.

    Inverse of :func:`laser_diode_power_fraction` on the lasing branch; the sub-threshold
    LED region cannot be targeted (its output is not a defined power).
    """
    fraction = max(0.0, min(1.0, float(power_uw) / max(float(max_uw), 1e-12)))
    f_sp = 0.002
    if fraction <= f_sp:
        return 0.0
    d_th = max(1.0, min(95.0, float(threshold_pct)))
    drive = d_th + (100.0 - d_th) * (fraction - f_sp) / (1.0 - f_sp)
    return max(0.0, min(100.0, drive))


#: Default excitation power per wavelength (µW): the blue 488 nm and the red 640 nm head.
DEFAULT_LASER_TARGETS_UW = {488: 60.0, 640: 25.0}


class SimShutters:
    """In-memory shutter readback and summed average-power diode."""
    def __init__(self, laser):
        self.laser=laser
        self._values={f'open_{name}':False for name in ('excitation','green','red')}
        self._marked=None
        self.closed=False
        self.stuck=False
        self.diode_stale=False

    def get_parameter(self, name, channel=-1):
        if name in self._values:return float(self._values[name])
        if name.startswith('reported_'):
            return float(self._values['open_'+name[9:]]) if not self.stuck else -1.
        if name=='diode_raw':
            state=self.laser.state()
            if state.emission_blocked or not self._values['open_excitation']:return 20.
            return 20.+sum(
                (800. if laser_diode_threshold(h)>=45. else 1000.) * laser_diode_power_fraction(h.intensity_pct, laser_diode_threshold(h))
                for h in state.heads
                if state.oscillator.output_enabled[h.output]
            )
        if name=='diode_mean':
            if self.diode_stale or self._marked is None or time.monotonic()-self._marked<.01:return -1.
            return self.get_parameter('diode_raw')
        if name=='diode_mark':return 0.
        raise ValueError(f'Unknown simulated shutter parameter {name}')

    def set_parameter(self, name, value, channel=-1):
        if self.closed:raise ValueError('Simulated shutter box is closed.')
        if name in self._values:self._values[name]=bool(value)
        elif name=='diode_mark':self._marked=time.monotonic()
        else:raise ValueError(f'Cannot set simulated parameter {name}')

    def apply(self, values):
        for key,value in values.items():self.set_parameter(key,value)

    def settings(self):
        names=list(self._values)+[f'reported_{n}' for n in ('excitation','green','red')]+['diode_raw','diode_mean']
        return {name:self.get_parameter(name) for name in names}

    def schema(self):
        props={name:{'type':'boolean','default':False,'title':name[5:].capitalize(),
                     'description':'SIMULATED shutter; no hardware command is sent.'}
               for name in self._values}
        props.update({f'reported_{name}':{'type':'number','readOnly':True,
                      'description':'SIMULATED readback (1=open, 0=closed).'}
                      for name in ('excitation','green','red')})
        props['diode_raw']={'type':'number','readOnly':True,'description':'SIMULATED summed diode signal.'}
        return {'name':'Simulated shutters','kind':'device','channels':0,
                'params_schema':{'type':'object','properties':props}}

    def close(self):
        self._values={k:False for k in self._values}
        self.closed=True


class SimulationRig:
    """Explicit green/red heads, oscillator sequencer, shutters and photon source."""
    simulated=True
    shutter_section={'shutters':[{'name':'Excitation','role':'excitation'},
                                  {'name':'Green','role':'detector'},
                                  {'name':'Red','role':'detector'}],
                     'open_at_start':['Excitation','Green','Red']}

    def __init__(self):
        clock=SimulatedPieSource(duration_s=.1).info
        self.laser=SimLaser(heads=[('Green 488 nm',488),('Red 640 nm',640)],
                            base_hz=2/(clock.n_micro*clock.micro_res_s))
        self.laser.open()
        self.laser.set_oscillator(burst_lengths=[1,1,0,0,0,0,0,0],
            output_enabled=[True,True,False,False,False,False,False,False],
            sync_enabled=[True,False,False,False,False,False,False,False])
        self.shutters=SimShutters(self.laser)
        self.stage='sample'
        # Excitation is measured relative to the default powers (488 nm: 60 µW, 640 nm: 25 µW):
        # at the defaults the sample shows its calibrated brightness; less power dims it
        # proportionally, and above them the simulated signal saturates.
        self._default_gains=self._head_gains_at_defaults()

    def _head_gains_at_defaults(self,max_uw=1000.):
        gains={}
        for head in self.laser.state().heads:
            target=DEFAULT_LASER_TARGETS_UW.get(int(head.wavelength_nm)) if head.wavelength_nm else None
            if target is None:continue
            drive=laser_diode_drive_for_power(target,max_uw,laser_diode_threshold(head))
            gains[head.output]=laser_diode_power_fraction(drive,laser_diode_threshold(head))
        return gains

    def seed_power_book(self, book):
        for name, max_span, d_th in [('Green 488 nm', 1000., 35.), ('Red 640 nm', 800., 47.)]:
            if not book.points(name):
                book.add(name, 20., 0.)
                raw_th = 20. + max_span * 0.002
                book.add(name, raw_th, 2.)
                d_mid = d_th + (100. - d_th) * 0.5
                f_mid = laser_diode_power_fraction(d_mid, d_th)
                book.add(name, 20. + max_span * f_mid, round(1000. * f_mid, 1))
                book.add(name, 20. + max_span, 1000.)
        book.save()

    def apply_default_powers(self, max_uw: float = 1000.0) -> None:
        """Set every head's drive so it delivers its default power (488 nm: 60 µW, 640 nm: 25 µW).

        Emission is left as it is (blocked until the run needs light); this only sets the
        drive the user sees on the cards.
        """
        for head in self.laser.state().heads:
            target = DEFAULT_LASER_TARGETS_UW.get(int(head.wavelength_nm)) if head.wavelength_nm else None
            if target is None:
                continue
            drive = laser_diode_drive_for_power(
                target, max_uw, laser_diode_threshold(head))
            self.laser.set_head(head.slot, enabled=True, intensity_pct=drive)

    def default_protocol(self):
        return {'name':'SIMULATION ONLY — PIE practice','simulation':True,'kind':'fret',
                'filters':'SIMULATION: confirm green and red detection filters.',
                'splitter':'SIMULATION: confirm green/red beam splitter.',
                'dyes':'SIMULATED Rh110 / Alexa647 / FRET DNA; no real calibration.',
                'laser_targets_uw':{'Green 488 nm':60.,'Red 640 nm':25.},
                'seconds':.3,'min_photons':3,'irf_fwhm_max_ns':.5,'background_max_khz':5.}

    def source(self, populations=None, *, bg=(.2,.2), seed=1, realtime=True,
               stage=None, duration_s=None, speed=1., realism=None, scheme="pie"):
        stage=stage or self.stage
        # Stage defaults apply only when the caller brings no sample of its own: the guided
        # FCS stage, for instance, passes the model's N/tau_D/brightness sample and that
        # is what must be measured -- never silently replaced by another concentration.
        if stage=='green_reference' and populations is None:populations=(Population(0,1.,3.,1000.),)
        elif stage=='red_reference' and populations is None:populations=(Population(1,.5,3.,1000.),)
        elif stage=='buffer' and populations is None:populations=(Population(0,.5,0.,0.),)
        elif stage=='fcs' and populations is None:
            populations=(Population(0,.5,4.,150.),)
            scheme='two_color'
        elif stage=='water' and populations is None:populations=(Population(.5,.5,4.,1000.),)
        elif populations is None:populations=(Population(.25,.5,8.,4000.),Population(.75,.5,8.,4000.))
        source=SimulatedPieSource(populations,duration_s=duration_s,background_khz=bg,
            seed=seed,realtime=realtime,speed=speed,realism=realism or IDEAL,
            scheme=scheme,
            segment_s=min(1.,duration_s) if duration_s else 1.)
        return _RigSource(self,source,stage,seed)

    def close(self):
        self.laser.close()
        self.shutters.close()


class SimulatedImagingIllumination:
    """Gate only synthetic imaging events using the rig's green excitation and shutters.

    Imaging sources have no excitation identity or background labels. They model a
    single green-excited specimen, so all generated photons (including background)
    scale with green drive. Scan markers always pass unchanged. This approximation
    is intentionally confined to simulator sources, never recorded real photons.
    """
    def __init__(self, rig, source, *, seed=1):
        self.rig, self.source = rig, source
        self.rng = np.random.default_rng(int(seed) + 11937)
        self.info = replace(source.info, name=f'SIMULATED instrument: {source.info.name}')

    def __getattr__(self, name):
        return getattr(self.source, name)

    def start(self):
        self.source.start()

    def stop(self):
        self.source.stop()

    def status(self):
        return {**self.source.status(), 'simulation': True}

    def read(self, timeout=.2):
        batch = self.source.read(timeout)
        if batch is None:
            return None
        if batch.raw is not None:
            raise SourceUnavailable('Simulation illumination cannot filter raw instrument records.')
        state = self.rig.laser.state()
        head = state.heads[0]
        enabled = (not state.emission_blocked
                   and self.rig.shutters.get_parameter('reported_excitation') == 1
                   and state.oscillator.output_enabled[head.output]
                   and state.oscillator.burst_lengths[head.output] > 0)
        default = self.rig._default_gains.get(head.output, 0.)
        absolute = laser_diode_power_fraction(head.intensity_pct, laser_diode_threshold(head)) if enabled else 0.
        gain = (absolute / default) if (enabled and default > 0.) else absolute
        event = batch.event
        marker = np.zeros(len(batch.macro), dtype=bool) if event is None else event != 0
        keep = marker | (self.rng.random(len(batch.macro)) < gain)
        for channel, name in enumerate(('green', 'red')):
            if self.rig.shutters.get_parameter('reported_' + name) != 1:
                keep &= marker | (batch.channel != channel)
        return PhotonBatch(batch.macro[keep], batch.micro[keep], batch.channel[keep],
                           truth=None if batch.truth is None else batch.truth[keep],
                           event=None if event is None else event[keep])


class _RigSource(PhotonSource):
    def __init__(self, rig, source, stage, seed):
        self.rig,self.source,self.stage=rig,source,stage
        self.duration_s=source.duration_s
        self.stops_itself=self.duration_s is not None
        self.rng=np.random.default_rng(seed+8123)
        osc=rig.laser.state().oscillator
        self._osc=osc
        period=sum(osc.burst_lengths)/osc.pulse_rate_hz
        n_micro=int(round(period/source.info.micro_res_s))
        if not 2<=n_micro<=32768:
            raise SourceUnavailable('Simulated sequence exceeds the T3 microtime range; shorten the sequence or change the clock.')
        self.info=replace(source.info,name=f'SIMULATED complete PIE instrument ({stage})',n_micro=n_micro)
        self._rates=[0.,0.,0.]

    def start(self):self.source.start()
    def stop(self):self.source.stop()
    @property
    def finished(self):return self.source.finished

    def status(self):
        return {**self.source.status(),'simulation':True,'count_rates_hz':list(self._rates)}

    def read(self, timeout=.2):
        batch=self.source.read(timeout)
        if batch is None:return None
        state=self.rig.laser.state()
        osc=state.oscillator
        # A changed clock cannot be written into a file with the old timebase.
        for name in ('base_hz','divider','burst_lengths','delays_ns'):
            if getattr(osc,name)!=getattr(self._osc,name):
                raise SourceUnavailable('Stop the simulated recording before changing its sequencer clock.')
        # Every labeled molecule photon is excitation-driven — FRET species, donor-only,
        # acceptor-only and aggregate states alike — so all of them scale with their exciting
        # head's output; with the laser off none of them may pass (only detector background).
        signal=batch.truth>=0
        if getattr(self.source, 'scheme', 'pie') == 'pie':
            red=batch.micro>=self.source.info.n_micro//2
            source_head=red.astype(int)
        else:
            source_head=np.zeros(len(batch), dtype=int)
        gain=np.zeros(2)
        if not state.emission_blocked and self.rig.shutters.get_parameter('reported_excitation')==1:
            for i,h in enumerate(state.heads):
                if osc.output_enabled[h.output] and osc.burst_lengths[h.output]>0:
                    # relative to the default power: 1.0 at 60/25 µW, dimmer below, saturated above
                    default=self.rig._default_gains.get(h.output,0.)
                    absolute=laser_diode_power_fraction(h.intensity_pct, laser_diode_threshold(h))
                    gain[i]=(absolute/default) if default>0. else absolute
        keep=(~signal)|(self.rng.random(len(batch))<gain[source_head])
        for channel,name in enumerate(('green','red')):
            if self.rig.shutters.get_parameter('reported_'+name)!=1:
                keep &= batch.channel!=channel
        micro=batch.micro.astype(np.int64).copy()
        decay=(micro%(self.source.info.n_micro//2))*self.source.info.micro_res_s
        if self.stage=='water':
            decay[signal]=np.maximum(0.,self.rng.normal(.2e-9,.06e-9,int(signal.sum())))
        for i in (0,1):
            sel=signal&(source_head==i)
            n=int(sel.sum())
            length=osc.burst_lengths[i]
            if n and length>0:
                pulse=self.rng.integers(length,size=n)
                start=(sum(osc.burst_lengths[:i])+pulse)/osc.pulse_rate_hz + osc.delays_ns[i]*1e-9
                if state.heads[i].pulsed:
                    micro[sel]=np.floor((start+decay[sel])/self.info.micro_res_s).astype(np.int64)%self.info.n_micro
                else:micro[sel]=self.rng.integers(self.info.n_micro,size=n)
        bg=~signal
        micro[bg]=self.rng.integers(self.info.n_micro,size=int(bg.sum()))
        self._rates=[osc.pulse_rate_hz/max(1,sum(osc.burst_lengths)),
                     float(np.sum(keep&(batch.channel==0)))/self.source.batch_s,
                     float(np.sum(keep&(batch.channel==1)))/self.source.batch_s]
        return PhotonBatch(batch.macro[keep],micro[keep].astype(np.uint16),
                           batch.channel[keep],batch.truth[keep])
