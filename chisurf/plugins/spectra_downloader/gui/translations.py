def install():
    """Register ChiSurf's catalogues (the translations of every string above) with :mod:`emtk.i18n`."""
    from chisurf.emtk.i18n import install as install_catalogues

    install_catalogues()


def tr(text):
    """Translate *text* through ChiSurf's catalogue."""
    return i18n.tr(text)
