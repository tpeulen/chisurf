#: Drawn for anything not in :data:`GLYPHS`. A hollow box, deliberately: a
#: missing character that renders as a space is one nobody reports.
MISSING = (".......//.#####.//.#...#.//.#...#.//.#...#.//.#...#.//.#...#.//.#####."
           "//.......//.......//.......")

#: How far the shadow is offset, in font pixels. One, down and to the right.
SHADOW = 1


def bitmap(char: str) -> np.ndarray:
    """One glyph as a mask, in its full authoring box.

    Parameters
    ----------
    char : str
        A single character.

    Returns
    -------
    numpy.ndarray
        ``(HEIGHT, WIDTH)`` bool, True where there is ink.
    """
    rows = GLYPHS.get(char, MISSING).split("//")
    grid = np.zeros((HEIGHT, WIDTH), dtype=bool)
    for y, row in enumerate(rows[:HEIGHT]):
        for x, cell in enumerate(row[:WIDTH]):
            grid[y, x] = cell == "#"
    return grid


def extent(char: str) -> tuple[int, int]:
    """Where a glyph's ink starts and how wide it is.

    This is where the proportional spacing comes from, and it costs nothing
    because it is *measured* from the art rather than declared beside it: a
    width table maintained by hand goes wrong the first time somebody nudges a
    stem, and goes wrong silently.

    Parameters
    ----------
    char : str
        A single character.

    Returns
    -------
    tuple of int
        ``(first inked column, number of columns)``. A blank glyph reports
        ``(0, SPACE)``.
    """
    columns = np.flatnonzero(bitmap(char).any(axis=0))
    if not len(columns):
        return 0, SPACE
    return int(columns[0]), int(columns[-1] - columns[0] + 1)


def metrics() -> dict[str, tuple[int, int, int]]:
    """Per-character atlas placement and advance.

    Returns
    -------
    dict
        ``char -> (atlas x, ink width, advance)``, all in font pixels. The
        advance is the ink plus :data:`GAP`, which is what makes ``i`` narrow
        and ``m`` wide without a hand-maintained width table.
    """
    table: dict[str, tuple[int, int, int]] = {}
    cursor = 0
    for char in CHARSET:
        _, width = extent(char)
        table[char] = (cursor, width, width + GAP)
        cursor += width
    return table


def atlas(scale: int = SCALE) -> np.ndarray:
    """Every glyph in :data:`CHARSET`, trimmed to its ink and laid side by side.

    Parameters
    ----------
    scale : int, optional
        Atlas pixels per font pixel.

    Returns
    -------
    numpy.ndarray
        ``(HEIGHT * scale, total ink width * scale)`` uint8, 0 or 255.
    """
    scale = max(1, int(scale))
    strips = []
    for char in CHARSET:
        left, width = extent(char)
        strips.append(bitmap(char)[:, left:left + width])
    grid = np.concatenate(strips, axis=1)
    grid = np.repeat(np.repeat(grid, scale, axis=0), scale, axis=1)
    return (grid * 255).astype(np.uint8)


def validate() -> list[str]:
    """Check every glyph is the right shape.

    A row of the wrong length silently truncates or leaves a column blank, and
    the result is a letter that looks *nearly* right -- which is exactly the
    kind of thing nobody spots in a screenshot but everybody feels.

    Returns
    -------
    list of str
        One complaint per malformed glyph; empty when the table is sound.
    """
    problems = []
    for char, art in GLYPHS.items():
        rows = art.split("//")
        if len(rows) != HEIGHT:
            problems.append(f"{char!r}: {len(rows)} rows, expected {HEIGHT}")
        for index, row in enumerate(rows):
            if len(row) != WIDTH:
                problems.append(f"{char!r} row {index}: {len(row)} wide, expected {WIDTH}")
            if set(row) - {"#", "."}:
                problems.append(f"{char!r} row {index}: unexpected characters")
    return problems
