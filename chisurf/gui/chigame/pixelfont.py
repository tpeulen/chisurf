"""The typeface, authored as string art.

chigame drew text by rasterising the platform's font through Qt, and the result
was the worst-looking thing in every screenshot. Two reasons, and the first is a
plain bug: ``QFontDatabase.systemFont(FixedFont)`` returns ``.AppleSystemUIFont``
on this platform -- a **proportional** face -- and setting ``setFixedPitch(True)``
afterwards does not change which face was resolved. Every glyph was then drawn
into a fixed cell the width of an ``M``, so an ``i`` floated in the middle of
forty pixels of nothing. That is the spindly, over-spaced look: ``s e t t l e d``.

The face is authored here instead, for the reasons the sprites and the room maps
are: string art is the only form that survives code review. Somebody can see in a
diff that the ``g`` changed, and see how.

**Why it is 7x11 and not 5x7.** A 5x7 body is a Game Boy face -- four-bit, one
stroke per feature, no room for a curve to be a curve. The 16-bit machines used a
taller box, and three things follow from it: capitals get eight rows so ``S`` and
``G`` can actually turn, lower case gets a real x-height instead of four rows,
and the descenders on ``g``, ``j``, ``p``, ``q`` and ``y`` hang below the
baseline rather than being tucked onto it.

**Two things matter as much as the resolution**, and both are what separates a
console face from a terminal one:

* **Proportional widths.** The art is authored in a 7-wide box and then *trimmed
  to its ink*, so ``i`` takes one column and ``m`` takes seven. Monospace is the
  single loudest tell of a font that was not designed, and it costs nothing here
  because the widths are measured from the art rather than declared.
* **A drop shadow.** Console dialogue is drawn twice, one pixel down and right,
  in a dark tone. It is why that text stays readable over any background, and it
  is most of why it reads as *of* the period rather than merely low-resolution.

Licensing note, since this replaced a proposal to ship a real font: nothing here
is anybody else's. It is one file of ``#`` and ``.``.
"""

