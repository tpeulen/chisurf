def _normalized(a: np.ndarray, axis: int | None = None) -> np.ndarray:
    """Return ``a`` scaled so that it sums to one along ``axis``.

    Sums of zero are left as zero rows rather than producing ``nan``.
    """
    a = np.asarray(a, dtype=float)
    total = a.sum(axis=axis, keepdims=axis is not None)
    total = np.where(total == 0, 1.0, total)
    return a / total


def _check_random_state(seed) -> np.random.Generator:
    """Turn ``seed`` (``None``, an int, or a generator) into a :class:`numpy.random.Generator`."""
    if seed is None or isinstance(seed, (int, np.integer)):
        return np.random.default_rng(seed)
    if isinstance(seed, np.random.Generator):
        return seed
    if isinstance(seed, np.random.RandomState):
        return np.random.default_rng(seed.randint(0, 2**32 - 1))
    raise ValueError(f"{seed!r} cannot be used to seed a random number generator")


def _split_sequences(X: np.ndarray, lengths: Sequence[int] | None) -> Iterator[np.ndarray]:
    """Yield the individual sequences packed row-wise into ``X``."""
    if lengths is None:
        yield X
        return
    ends = np.cumsum(np.asarray(lengths, dtype=int))
    if ends[-1] != len(X):
        raise ValueError(f"lengths sum to {ends[-1]} but X has {len(X)} samples")
    starts = np.concatenate([[0], ends[:-1]])
    for start, end in zip(starts, ends):
        yield X[start:end]


def _log_gaussian_density(
    X: np.ndarray,
    means: np.ndarray,
    covars: np.ndarray,
    covariance_type: str,
    min_covar: float = 1e-7,
) -> np.ndarray:
    """Evaluate the log emission density of every state at every sample.

    Parameters
    ----------
    X : numpy.ndarray
        Samples, shape ``(n_samples, n_features)``.
    means : numpy.ndarray
        State means, shape ``(n_components, n_features)``.
    covars : numpy.ndarray
        Covariances in the compact layout of ``covariance_type`` (see
        :attr:`GaussianHMM.covars_`).
    covariance_type : str
        One of :data:`COVARIANCE_TYPES`.
    min_covar : float
        Ridge added to a full covariance that is not positive definite, as a
        last attempt before giving up.

    Returns
    -------
    numpy.ndarray
        Log densities, shape ``(n_samples, n_components)``.
    """
    n_components, n_features = means.shape
    if covariance_type == "spherical":
        covars = np.repeat(np.asarray(covars)[:, None], n_features, axis=1)
        covariance_type = "diag"
    if covariance_type == "diag":
        # Guard the degenerate covariance case against 0 * log 0 = nan.
        covars = np.maximum(covars, np.finfo(float).tiny)
        with np.errstate(over="ignore"):
            return -0.5 * (
                n_features * np.log(2 * np.pi)
                + np.log(covars).sum(axis=-1)
                + ((X[:, None, :] - means) ** 2 / covars).sum(axis=-1)
            )
    if covariance_type == "tied":
        covars = np.broadcast_to(covars, (n_components, n_features, n_features))
    log_prob = np.empty((len(X), n_components))
    for c, (mu, cv) in enumerate(zip(means, covars)):
        try:
            cv_chol = linalg.cholesky(cv, lower=True)
        except linalg.LinAlgError:
            # A state that captured too few samples can go singular; nudge it.
            try:
                cv_chol = linalg.cholesky(cv + min_covar * np.eye(n_features), lower=True)
            except linalg.LinAlgError as err:
                raise ValueError("covariances must be symmetric positive-definite") from err
        cv_log_det = 2 * np.sum(np.log(np.diagonal(cv_chol)))
        cv_sol = linalg.solve_triangular(cv_chol, (X - mu).T, lower=True).T
        log_prob[:, c] = -0.5 * (
            n_features * np.log(2 * np.pi) + (cv_sol**2).sum(axis=1) + cv_log_det
        )
    return log_prob


@nb.jit(nopython=True, nogil=True, fastmath=True)
def _squared_distances(X: np.ndarray, center: np.ndarray, out: np.ndarray) -> None:
    """Fill ``out`` with the squared distance from every row of ``X`` to ``center``."""
    n_samples, n_features = X.shape
    for t in range(n_samples):
        acc = 0.0
        for j in range(n_features):
            diff = X[t, j] - center[j]
            acc += diff * diff
        out[t] = acc


@nb.jit(nopython=True, nogil=True, fastmath=True)
def _kmeanspp_seed(X: np.ndarray, n_clusters: int, uniforms: np.ndarray) -> np.ndarray:
    """Choose ``n_clusters`` initial centres with the greedy k-means++ rule.

    Each further centre is sampled from the data with a probability
    proportional to its squared distance from the closest centre chosen so far.
    Several candidates are drawn per centre and the one that lowers the total
    squared distance the most is kept -- the greedy variant, which is markedly
    less likely to strand a centre than taking the first draw. ``uniforms``
    supplies the pre-drawn variates, so the caller keeps control of the random
    stream.
    """
    n_samples, n_features = X.shape
    n_trials = uniforms.shape[0] // n_clusters
    centers = np.empty((n_clusters, n_features))
    index = min(int(uniforms[0] * n_samples), n_samples - 1)
    centers[0] = X[index]
    closest = np.empty(n_samples)
    _squared_distances(X, centers[0], closest)
    candidate = np.empty(n_samples)
    for c in range(1, n_clusters):
        total = 0.0
        for t in range(n_samples):
            total += closest[t]
        best_potential = np.inf
        best_index = -1
        for trial in range(n_trials):
            uniform = uniforms[c * n_trials + trial]
            if total <= 0.0:
                index = min(int(uniform * n_samples), n_samples - 1)
            else:
                target = uniform * total
                acc = 0.0
                index = n_samples - 1
                for t in range(n_samples):
                    acc += closest[t]
                    if acc >= target:
                        index = t
                        break
            _squared_distances(X, X[index], candidate)
            potential = 0.0
            for t in range(n_samples):
                potential += min(candidate[t], closest[t])
            if potential < best_potential:
                best_potential = potential
                best_index = index
        centers[c] = X[best_index]
        _squared_distances(X, centers[c], candidate)
        for t in range(n_samples):
            if candidate[t] < closest[t]:
                closest[t] = candidate[t]
    return centers


@nb.jit(nopython=True, nogil=True, fastmath=True)
def _kmeans_lloyd(
    X: np.ndarray, centers: np.ndarray, labels: np.ndarray, max_iter: int, tol: float
) -> float:
    """Run Lloyd's algorithm in place on ``centers``/``labels``, returning the inertia.

    Assignment and centroid accumulation share one pass over the samples, so no
    ``(n_samples, n_clusters)`` distance matrix is ever materialised.
    """
    n_samples, n_features = X.shape
    n_clusters = centers.shape[0]
    labels[:] = -1
    sums = np.empty((n_clusters, n_features))
    counts = np.empty(n_clusters)
    inertia = 0.0
    for _ in range(max_iter):
        sums[:, :] = 0.0
        counts[:] = 0.0
        inertia = 0.0
        n_changed = 0
        worst_distance = -1.0
        worst_index = 0
        for t in range(n_samples):
            best = np.inf
            best_c = 0
            for c in range(n_clusters):
                acc = 0.0
                for j in range(n_features):
                    diff = X[t, j] - centers[c, j]
                    acc += diff * diff
                if acc < best:
                    best = acc
                    best_c = c
            if labels[t] != best_c:
                labels[t] = best_c
                n_changed += 1
            inertia += best
            counts[best_c] += 1.0
            for j in range(n_features):
                sums[best_c, j] += X[t, j]
            if best > worst_distance:
                worst_distance = best
                worst_index = t
        shift = 0.0
        for c in range(n_clusters):
            if counts[c] > 0.0:
                for j in range(n_features):
                    updated = sums[c, j] / counts[c]
                    diff = updated - centers[c, j]
                    shift += diff * diff
                    centers[c, j] = updated
            else:
                # Re-seed an emptied cluster on the worst-explained sample.
                for j in range(n_features):
                    centers[c, j] = X[worst_index, j]
                shift += tol + 1.0
        if n_changed == 0 or shift <= tol * tol:
            break
    return inertia


def _kmeans(
    X: np.ndarray,
    n_clusters: int,
    random_state: np.random.Generator,
    n_init: int = 10,
    max_iter: int = 300,
    tol: float = 1e-4,
) -> tuple[np.ndarray, np.ndarray]:
    """Cluster ``X`` with k-means++ seeded Lloyd iterations.

    Used to place the initial state means *and* -- through the labels it
    returns -- the initial transitions and covariances. The EM iterations take
    over from there, so a plain implementation is enough, and it keeps this
    module free of a machine-learning dependency.

    Parameters
    ----------
    X : numpy.ndarray
        Samples, shape ``(n_samples, n_features)``.
    n_clusters : int
        Number of centres to place.
    random_state : numpy.random.Generator
        Source of randomness for the seeding.
    n_init : int
        Number of restarts; the run with the lowest inertia wins.
    max_iter : int
        Maximum Lloyd iterations per restart.
    tol : float
        Stop a restart once the centres move less than this (Frobenius norm).

    Returns
    -------
    centers : numpy.ndarray
        Cluster centres, shape ``(n_clusters, n_features)``.
    labels : numpy.ndarray
        Index of the closest centre per sample, shape ``(n_samples, )``.
    """
    X = np.ascontiguousarray(X, dtype=float)
    n_samples = len(X)
    if n_samples <= n_clusters:
        centers = np.repeat(X.mean(axis=0)[None, :], n_clusters, axis=0)
        centers[:n_samples] = X
        return centers, np.arange(n_samples) % n_clusters

    # Candidates per centre for the greedy seeding, as in the reference
    # implementations: enough to matter, few enough to stay cheap.
    n_trials = 2 + int(np.log(n_clusters))
    labels = np.empty(n_samples, dtype=np.int64)
    best, best_inertia = None, np.inf
    for _ in range(n_init):
        centers = _kmeanspp_seed(
            X, n_clusters, random_state.random(n_clusters * n_trials)
        )
        inertia = _kmeans_lloyd(X, centers, labels, max_iter, tol)
        if inertia < best_inertia:
            best, best_inertia = (centers, labels.copy()), inertia
    return best


def _project_simplexes(
    theta: np.ndarray, reference: np.ndarray, n_components: int
) -> np.ndarray:
    """Return ``theta`` with its probability blocks projected back onto the simplex.

    Clipping alone would turn an overshot probability into a hard zero, and a
    zero is permanent: the M-step keeps it, so that a state a constrained model
    is allowed to reach could silently become unreachable. Anything positive in
    ``reference`` therefore keeps a floor. The remaining blocks -- means, and
    covariances in the unconstrained space of :func:`_covars_to_free` -- are
    feasible for any real value and pass through.
    """
    theta = theta.copy()
    n_probabilities = n_components + n_components * n_components
    blocks = theta[:n_probabilities]
    np.clip(blocks, 0.0, None, out=blocks)
    floor = np.finfo(float).eps / n_components
    np.copyto(blocks, floor, where=(blocks <= 0) & (reference[:n_probabilities] > 0))
    # The start distribution and every transition row share the same treatment.
    rows = blocks.reshape(n_components + 1, n_components)
    # A block that the extrapolation emptied carries no information; spread it.
    rows[rows.sum(axis=1) == 0] = 1.0 / n_components
    theta[:n_probabilities] = _normalized(rows, axis=1).ravel()
    return theta


def _covars_to_free(covars: np.ndarray, covariance_type: str) -> np.ndarray:
    """Map covariances to an unconstrained vector for SQUAREM extrapolation.

    Variances become log-variances and matrices become their lower Cholesky
    factor with a log-diagonal, so that *any* real vector maps back to a valid
    positive-definite covariance.
    """
    if covariance_type in ("spherical", "diag"):
        return np.log(np.maximum(covars, np.finfo(float).tiny)).ravel()
    matrices = covars if covariance_type == "full" else covars[None]
    try:
        chol = np.linalg.cholesky(matrices)
    except np.linalg.LinAlgError:
        # A state that captured almost no samples can lose definiteness; a
        # ridge keeps the extrapolation going instead of aborting the fit.
        n_features = matrices.shape[-1]
        ridge = 1e-6 * np.trace(matrices, axis1=1, axis2=2).max() / n_features
        logger.debug("Ridging a non positive-definite covariance by %g", ridge)
        chol = np.linalg.cholesky(matrices + ridge * np.eye(n_features))
    diagonal = np.arange(matrices.shape[-1])
    chol[:, diagonal, diagonal] = np.log(chol[:, diagonal, diagonal])
    return chol.ravel()


def _covars_from_free(
    free: np.ndarray, covariance_type: str, n_components: int, n_features: int
) -> np.ndarray:
    """Invert :func:`_covars_to_free`."""
    if covariance_type == "spherical":
        return np.exp(free)
    if covariance_type == "diag":
        return np.exp(free).reshape(n_components, n_features)
    n_matrices = n_components if covariance_type == "full" else 1
    chol = np.tril(free.reshape(n_matrices, n_features, n_features))
    diagonal = np.arange(n_features)
    chol[:, diagonal, diagonal] = np.exp(chol[:, diagonal, diagonal])
    covars = chol @ chol.transpose(0, 2, 1)
    return covars if covariance_type == "full" else covars[0]


class ConvergenceMonitor:
    """Track the EM log-likelihood and decide when Baum-Welch has converged.

    Parameters
    ----------
    tol : float
        Convergence threshold on the log-likelihood gain between two
        consecutive iterations.
    n_iter : int
        Maximum number of iterations.
    verbose : bool
        Whether to print a per-iteration report to :data:`sys.stderr`.

    Attributes
    ----------
    history : collections.deque
        Log-likelihood of every iteration performed so far.
    iter : int
        Number of iterations performed.
    """

    _template = "{iter:>10d} {log_prob:>16.8f} {delta:>+16.8f}"

    def __init__(self, tol: float, n_iter: int, verbose: bool = False):
        self.tol = tol
        self.n_iter = n_iter
        self.verbose = verbose
        self.history: deque[float] = deque(maxlen=2)
        self.iter = 0

    def __repr__(self) -> str:
        """Return a reproducible representation including the log-likelihood history."""
        return (
            f"{type(self).__name__}(tol={self.tol}, n_iter={self.n_iter}, "
            f"verbose={self.verbose}, history={list(self.history)}, iter={self.iter})"
        )

    def reset(self) -> None:
        """Forget the history of a previous fit."""
        self.iter = 0
        self.history.clear()

    def report(self, log_prob: float) -> None:
        """Record the log-likelihood of the iteration that just finished."""
        if self.verbose:
            delta = log_prob - self.history[-1] if self.history else np.nan
            print(
                self._template.format(iter=self.iter + 1, log_prob=log_prob, delta=delta),
                file=sys.stderr,
            )
        # EM cannot decrease the likelihood; allow only for rounding noise.
        precision = np.finfo(float).eps ** 0.5
        if self.history and (log_prob - self.history[-1]) < -precision:
            logger.warning(
                "HMM is not converging: log-likelihood dropped from %s to %s",
                self.history[-1],
                log_prob,
            )
        self.history.append(log_prob)
        self.iter += 1

    @property
    def converged(self) -> bool:
        """Whether the iteration limit or the tolerance has been reached."""
        return self.iter == self.n_iter or (
            len(self.history) == 2 and self.history[1] - self.history[0] < self.tol
        )


