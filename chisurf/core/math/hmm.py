def _project_simplexes(theta: np.ndarray, reference: np.ndarray, n_components: int) -> np.ndarray:
    """Return ``theta`` with its probability blocks projected back onto the simplex.

    Clipping alone would turn an overshot probability into a hard zero, and a
    zero is permanent: the M-step keeps it, so that a state a constrained model
    is allowed to reach could silently become unreachable. Anything positive in
    ``reference`` therefore keeps a floor. The remaining blocks -- means, and
    covariances in the unconstrained space of :func:`_covars_to_free` -- are
    feasible for any real value and pass through.
    """
    theta = theta.copy()
    n_probabilities = n_components + n_components * n_components
    blocks = theta[:n_probabilities]
    np.clip(blocks, 0.0, None, out=blocks)
    floor = np.finfo(float).eps / n_components
    np.copyto(blocks, floor, where=(blocks <= 0) & (reference[:n_probabilities] > 0))
    # The start distribution and every transition row share the same treatment.
    rows = blocks.reshape(n_components + 1, n_components)
    # A block that the extrapolation emptied carries no information; spread it.
    rows[rows.sum(axis=1) == 0] = 1.0 / n_components
    theta[:n_probabilities] = _normalized(rows, axis=1).ravel()
    return theta


def _covars_to_free(covars: np.ndarray, covariance_type: str) -> np.ndarray:
    """Map covariances to an unconstrained vector for SQUAREM extrapolation.

    Variances become log-variances and matrices become their lower Cholesky
    factor with a log-diagonal, so that *any* real vector maps back to a valid
    positive-definite covariance.
    """
    if covariance_type in ("spherical", "diag"):
        return np.log(np.maximum(covars, np.finfo(float).tiny)).ravel()
    matrices = covars if covariance_type == "full" else covars[None]
    try:
        chol = np.linalg.cholesky(matrices)
    except np.linalg.LinAlgError:
        # A state that captured almost no samples can lose definiteness; a
        # ridge keeps the extrapolation going instead of aborting the fit.
        n_features = matrices.shape[-1]
        ridge = 1e-6 * np.trace(matrices, axis1=1, axis2=2).max() / n_features
        logger.debug("Ridging a non positive-definite covariance by %g", ridge)
        chol = np.linalg.cholesky(matrices + ridge * np.eye(n_features))
    diagonal = np.arange(matrices.shape[-1])
    chol[:, diagonal, diagonal] = np.log(chol[:, diagonal, diagonal])
    return chol.ravel()


def _covars_from_free(
    free: np.ndarray, covariance_type: str, n_components: int, n_features: int
) -> np.ndarray:
    """Invert :func:`_covars_to_free`."""
    if covariance_type == "spherical":
        return np.exp(free)
    if covariance_type == "diag":
        return np.exp(free).reshape(n_components, n_features)
    n_matrices = n_components if covariance_type == "full" else 1
    chol = np.tril(free.reshape(n_matrices, n_features, n_features))
    diagonal = np.arange(n_features)
    chol[:, diagonal, diagonal] = np.exp(chol[:, diagonal, diagonal])
    covars = chol @ chol.transpose(0, 2, 1)
    return covars if covariance_type == "full" else covars[0]


class ConvergenceMonitor:
    """Track the EM log-likelihood and decide when Baum-Welch has converged.

    Parameters
    ----------
    tol : float
        Convergence threshold on the log-likelihood gain between two
        consecutive iterations.
    n_iter : int
        Maximum number of iterations.
    verbose : bool
        Whether to print a per-iteration report to :data:`sys.stderr`.

    Attributes
    ----------
    history : collections.deque
        Log-likelihood of every iteration performed so far.
    iter : int
        Number of iterations performed.
    """

    _template = "{iter:>10d} {log_prob:>16.8f} {delta:>+16.8f}"

    def __init__(self, tol: float, n_iter: int, verbose: bool = False):
        self.tol = tol
        self.n_iter = n_iter
        self.verbose = verbose
        self.history: deque[float] = deque(maxlen=2)
        self.iter = 0

    def __repr__(self) -> str:
        """Return a reproducible representation including the log-likelihood history."""
        return (
            f"{type(self).__name__}(tol={self.tol}, n_iter={self.n_iter}, "
            f"verbose={self.verbose}, history={list(self.history)}, iter={self.iter})"
        )

    def reset(self) -> None:
        """Forget the history of a previous fit."""
        self.iter = 0
        self.history.clear()

    @staticmethod
    def _gain(current: float, previous: float) -> float:
        """Return the log-likelihood gain between two iterations.

        Plain subtraction is wrong at the one place it matters: a model that
        assigns zero probability to the data scores ``-inf`` twice in a row,
        and ``-inf - (-inf)`` is ``nan``. Every comparison against ``nan`` is
        false, so the run neither converges nor warns -- it silently spends
        the whole iteration budget. Two equal scores are no gain, which is
        what "converged" means, whether or not they are finite.
        """
        if current == previous:
            return 0.0
        return current - previous

    def report(self, log_prob: float) -> None:
        """Record the log-likelihood of the iteration that just finished."""
        if self.verbose:
            delta = self._gain(log_prob, self.history[-1]) if self.history else np.nan
            print(
                self._template.format(iter=self.iter + 1, log_prob=log_prob, delta=delta),
                file=sys.stderr,
            )
        # A non-finite score is not a convergence result: the model explains
        # none of the data. Say so rather than returning a converged-looking
        # fit whose score, aic and bic are all -inf.
        if not np.isfinite(log_prob):
            logger.warning(
                "HMM log-likelihood is %s: the model assigns zero probability "
                "to the data (a structural zero or an emptied start "
                "distribution makes every sequence impossible).",
                log_prob,
            )
        # EM cannot decrease the likelihood; allow only for rounding noise.
        precision = np.finfo(float).eps ** 0.5
        if self.history and self._gain(log_prob, self.history[-1]) < -precision:
            logger.warning(
                "HMM is not converging: log-likelihood dropped from %s to %s",
                self.history[-1],
                log_prob,
            )
        self.history.append(log_prob)
        self.iter += 1

    @property
    def converged(self) -> bool:
        """Whether the iteration limit or the tolerance has been reached."""
        return self.iter == self.n_iter or (
            len(self.history) == 2 and self._gain(self.history[1], self.history[0]) < self.tol
        )


