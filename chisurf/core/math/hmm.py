#: Emission covariance parameterisations understood by :class:`GaussianHMM`.
COVARIANCE_TYPES = ("spherical", "diag", "full", "tied")

#: A SQUAREM cycle costs three EM maps. It is counted as wasted when it gains
#: less than this multiple of the cycle's own first EM step -- EM gains shrink
#: as the fixed point nears, so plain maps could not have done better either.
SQUAREM_MIN_GAIN_FACTOR = 1.0

#: Number of consecutive wasted cycles after which acceleration is abandoned and
#: the remaining budget is spent on plain EM. Kept high: acceleration routinely
#: spends a few modest cycles before a large jump.
SQUAREM_PATIENCE = 4


