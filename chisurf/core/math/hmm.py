r"""Hidden Markov models with Gaussian emissions, fitted by Baum-Welch.

A hidden Markov model describes a sequence of observations
:math:`x_1 \dots x_T` as generated by an unobserved Markov chain of discrete
states :math:`z_1 \dots z_T`. It is parameterised by an initial-state
distribution :math:`\pi_i = P(z_1 = i)`, a transition matrix
:math:`A_{ij} = P(z_{t+1} = j \mid z_t = i)` and, here, one multivariate normal
emission density per state,

.. math::

    P(x_t \mid z_t = i) = \mathcal{N}(x_t; \mu_i, \Sigma_i).

ChiSurf uses this for binned single-molecule traces: each time bin carries the
photon counts of one or more detection channels, and the states are the
conformational/photophysical states the molecule dwells in. The state path
recovered by :meth:`GaussianHMM.predict` gives dwell times and a transition
matrix; :meth:`GaussianHMM.bic` selects how many states the data supports.

Everything here is maximum-likelihood: parameters are estimated by the
Baum-Welch (EM) algorithm, with optional conjugate priors that act as
regularisers rather than as a full Bayesian treatment. The variational-Bayes
counterpart used for empirical-Bayes FRET analysis lives in the ebFRET plugin
(``chisurf/plugins/burst/burst_ebfret/core/hmm.py``); the photon-by-photon
variant is H2MM.

The forward-backward recursions run in log space, so long traces do not
underflow, and the time-stepping loops are the photon library's compiled
lattice.

Where the analysis lives
------------------------
This module is the *estimator*: fit, score, decode, sample, AIC/BIC. Its
surface deliberately uses the vocabulary of the general HMM literature
(``n_components``, ``covariance_type``, ``transmat_``, ``predict``).

It is **not** where an analysis should be assembled. Relabelling states by
brightness, defining a dwell time, converting transitions to rates and choosing
a state count are decisions that must not differ between two tools reporting
"state 1", so they live once in ``chisurf.plugins.core.hmm.core``, and the GUI
tool, the ``csc hmm`` CLI, the ``hmm.fit``/``hmm.scan`` RPC methods and the
intensity-trace tool all go through it. Call that, not this, unless you are
writing a new estimator-level feature.

Why this is written out rather than imported
--------------------------------------------
It replaced an external HMM package, and is 1.1x to 18x faster per E-step and
2x to 10x faster end to end at an equal or better optimum (the numbers, and the
script that produces them, are in ``docs/development/benchmarks.md`` and
``test/benchmarks/benchmark_hmm.py``). Three decisions account for that, and
each is a thing to preserve rather than an accident:

1. **One fused backward sweep** (:func:`_backward_posteriors_xi`). The backward
   lattice, the state posteriors and the expected transition counts all need
   the same quantity; computing and exponentiating it once, in one reverse
   pass, beats the textbook arrangement of three passes, and keeps two rows of
   the backward lattice alive instead of the whole ``(T, K)`` array.
2. **Data-driven initialisation** (:meth:`GaussianHMM._init`). Every parameter
   starts from one k-means clustering read as a hard-assignment state path.
   The usual random draw ignores the data, including its time ordering.
3. **SQUAREM acceleration** (:meth:`GaussianHMM._fit_squarem`), on by default.
   It reaches the same fixed point in a fraction of the maps wherever EM
   crawls, and steps aside when it stops paying.

Invariants a change must not break
----------------------------------
Each of these was a real defect first, so they are cheap to reintroduce:

* **Log space is load-bearing, and so are its infinities.** The compiled
  lattice guards against ``-inf``; fast-math licenses the compiler to assume no
  operand is infinite and deletes those guards. The library therefore builds
  that translation unit without it, and an all-``-inf`` frame is a test rather
  than a hope.
* **A frame that no state can explain gets a uniform posterior.** Its
  ``log_gamma`` row is all ``-inf``, and subtracting its own maximum yields
  ``nan``, which then spreads through the M-step into every later iteration.
  The ``-inf`` log-likelihood still reports the problem upstream.
* **A state with no posterior mass keeps its parameters.** Fitting more states
  than the data supports is a normal thing for a user to do; it must degrade,
  not produce ``nan`` means from ``0/0``.
* **Structural zeros are honoured; accidental ones are never created.** A zero
  in :attr:`~GaussianHMM.transmat_` is preserved by the M-step -- that is how a
  left-to-right chain stays a left-to-right chain -- so neither the
  initialisation nor SQUAREM's projection is allowed to introduce one, or a
  state becomes permanently unreachable.

Examples
--------
>>> import numpy as np
>>> from chisurf.core.math.hmm import GaussianHMM
>>> model = GaussianHMM(n_components=2, covariance_type="full", random_state=0)
>>> rng = np.random.default_rng(0)
>>> x = np.concatenate([rng.normal(0, 1, 200), rng.normal(10, 1, 200)])[:, None]
>>> states = model.fit(x).predict(x)
>>> np.round(np.sort(model.means_.ravel())).tolist()
[0.0, 10.0]

References
----------
.. [1] L. R. Rabiner, "A tutorial on hidden Markov models and selected
       applications in speech recognition", Proc. IEEE 77, 257-286 (1989).
.. [2] X. Huang, A. Acero, H.-W. Hon, "Spoken Language Processing",
       Prentice Hall (2001), pp. 443-445 (MAP re-estimation formulas).
"""

